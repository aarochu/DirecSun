#!/usr/bin/env python3
"""R3.5 Tests item 5: a read-only client receives only tlm.

    t4-readonly.py --url ws://direcsun.local/ws [--seconds 60] [--events estop|hall|arm]

The item: "A read-only client that never sends receives only tlm frames over 60 s,
while mode events are generated by a second client; the UI's ignored counter stays
0. Positive control: a client that has sent a ping receives those events."

Three clients, the box's maximum (close the console and any UI tab first):
- READER: the main UI in Chrome (--reader ui, default), which never sends. Chrome
  records every frame it receives; the UI's status line gives its ignored count.
  --reader raw uses a Python client that never sends instead.
- PINGER: sends exactly one ping at the start, then only listens. It is the
  positive control: it must receive the events.
- GENERATOR: causes events every --period seconds, by --events:
    estop  `estop` while SAFE. The firmware posts event mode SAFE cause ESTOP for
           every e-stop, even in SAFE (modes.cpp step 4, host test HT-8), and
           latches ESTOP until the next arm. Never arms. The default.
    hall   set_params bench_mode on, then hall_installed off and on (HALL_BYPASS
           notice events), restored at the end. Never arms. The firmware resets
           both at every boot anyway.
    arm    arm, ping for 1 s, disarm. ARMS THE BOX: needs --confirm-arm (RUNBOOK).

Verdict: READER got only tlm (and at least 95 % of 50 Hz), the UI's ignored counter
stayed 0 and the UI sent nothing; GENERATOR caused at least one event; PINGER
received every event GENERATOR received. If no event is generated at all, the
positive control fails and the run proves nothing, so it is a FAIL.
"""
import argparse
import asyncio
import json
import subprocess
import sys
import threading
import time

import r35common as rc

CONFIRM_VALUES = ("esc-unplugged", "julian-go")


async def generate(gen, kind, seconds, period, run, stop):
    """Cause events for `seconds`. Returns a list of (label, ack) for what was sent."""
    log = []
    loop = asyncio.get_running_loop()
    end = loop.time() + seconds
    if kind == "hall":
        last = gen.last_tlm() or {}
        if "HALL_BYPASS" in (last.get("flags") or []):
            return log, "the box is already in HALL_BYPASS: reboot it (both settings reset at boot) and rerun"
        ack, _ = await gen.cmd("set_params", params={"bench_mode": True})
        log.append(("bench_mode on", ack))
        if not ack or not ack.get("ok"):
            return log, f"set_params bench_mode refused: {ack}"
        bypass = False
        while loop.time() < end - period and not stop.is_set():
            bypass = not bypass
            ack, _ = await gen.cmd("set_params", params={"hall_installed": not bypass})
            log.append((f"hall_installed {not bypass}", ack))
            await asyncio.sleep(period)
        if bypass:
            ack, _ = await gen.cmd("set_params", params={"hall_installed": True})
            log.append(("hall_installed True (restore)", ack))
        ack, _ = await gen.cmd("set_params", params={"bench_mode": False})
        log.append(("bench_mode off (restore)", ack))
    elif kind == "estop":
        while loop.time() < end - 1.0 and not stop.is_set():
            ack, _ = await gen.cmd("estop")
            log.append(("estop", ack))
            await asyncio.sleep(period)
    elif kind == "arm":
        gen.start_pings(5)
        while loop.time() < end - 2.5 and not stop.is_set():
            ack, _ = await gen.cmd("arm")
            log.append(("arm", ack))
            await asyncio.sleep(1.0)
            ack, _ = await gen.cmd("disarm")
            log.append(("disarm", ack))
            await asyncio.sleep(max(0.0, period - 1.0))
        gen.stop_pings()
    remaining = end - loop.time()
    if remaining > 0:
        await asyncio.sleep(remaining)
    return log, None


async def session(args, run, reader_ready, stop):
    pinger = rc.Client("pinger", args.url)
    gen = rc.Client("generator", args.url)
    raw_reader = rc.Client("reader", args.url) if args.reader == "raw" else None
    clients = [c for c in (raw_reader, pinger, gen) if c]
    try:
        if raw_reader:
            await raw_reader.open()
        else:
            # Wait for the UI to be connected before anything else talks.
            for _ in range(600):
                if reader_ready.is_set() or stop.is_set():
                    break
                await asyncio.sleep(0.1)
            if not reader_ready.is_set():
                return clients, [], "the UI reader never connected"
        await pinger.open()
        await gen.open()
        await gen.wait_for(lambda m: m.get("type") == "tlm", 3.0)
        pong_index = len(pinger.frames)
        await pinger.ping()
        pong = await pinger.wait_for(lambda m: m.get("type") == "pong", 3.0, pong_index)
        run.check("pinger got its pong", pong is not None, f"{pong[1] if pong else 'no pong in 3 s'}")
        t_start = time.monotonic()
        log, problem = await generate(gen, args.events, args.seconds, args.period, run, stop)
        await asyncio.sleep(1.0)
        run.say(f"generator sent {len(log)} commands in {time.monotonic() - t_start:.1f} s")
        return clients, log, problem
    finally:
        if args.events == "arm" and gen.ws is not None and gen.closed_at is None:
            fresh = await gen.wait_for(lambda m: m.get("type") == "tlm", 0.5, len(gen.frames))
            if fresh is None or fresh[1].get("mode") != "SAFE":
                run.say(f"cleanup: box {fresh[1].get('mode') if fresh else 'unknown'}: sending estop")
                await gen.cmd("estop")
        for client in clients:
            await client.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--url", default="ws://direcsun.local/ws")
    parser.add_argument("--seconds", type=float, default=60.0)
    parser.add_argument("--events", choices=("estop", "hall", "arm"), default="estop")
    parser.add_argument("--period", type=float, default=3.0, help="seconds between generated events")
    parser.add_argument("--reader", choices=("ui", "raw"), default="ui")
    parser.add_argument("--confirm-arm", choices=CONFIRM_VALUES,
                        help="--events arm only: esc-unplugged, or julian-go (RUNBOOK, safety)")
    parser.add_argument("--out")
    args = parser.parse_args()
    if args.events == "arm" and not args.confirm_arm:
        print("t4-readonly: --events arm sends `arm` (SPINUP) every period. That can turn the motor if an ESC is\n"
              "powered and connected. Rerun with --confirm-arm esc-unplugged (the ESC is physically\n"
              "disconnected) or --confirm-arm julian-go (Julian said go for this run). Nothing was sent.")
        return 2
    run = rc.Run("t4-readonly", args.out)
    run.say(f"events by {args.events} every {args.period} s for {args.seconds:.0f} s; reader {args.reader}")

    reader_ready = threading.Event()
    stop = threading.Event()
    probe_result = {}

    def ui_reader():
        def on_line(line):
            if "CONNECTED" in line:
                reader_ready.set()
        try:
            with rc.ui_server(run) as base:
                probe_result.update(rc.probe(run, "watch", args.url, base, ["--watch-s", str(args.seconds + 8)],
                                             on_line=on_line, timeout=args.seconds + 150))
        except RuntimeError as exc:
            probe_result.update({"ok": False, "error": str(exc)})
        finally:
            stop.set()

    thread = None
    if args.reader == "ui":
        thread = threading.Thread(target=ui_reader, daemon=True)
        thread.start()
    try:
        clients, log, problem = asyncio.run(session(args, run, reader_ready, stop))
    except Exception as exc:  # noqa: BLE001 - a client that cannot connect is the finding
        stop.set()
        run.check("clients connect", False, f"{type(exc).__name__}: {exc}")
        if thread:
            thread.join(timeout=args.seconds + 180)
        return run.finish()
    if thread:
        thread.join(timeout=args.seconds + 180)
    if problem:
        run.check("events generated as planned", False, problem)
    by_name = {c.name: c for c in clients}
    pinger, gen = by_name["pinger"], by_name["generator"]

    # Reader.
    if args.reader == "ui":
        if not probe_result.get("ok"):
            run.check("UI reader", False, probe_result.get("error"))
        else:
            frames = probe_result.get("wsFrames", {})
            received = frames.get("received", {})
            tlm = received.get("tlm", 0)
            run.check("reader received only tlm", set(received) == {"tlm"},
                      f"Chrome saw {received}" + (f"; non-tlm {frames.get('receivedNonTlmSamples')[:3]}"
                                                  if set(received) - {"tlm"} else ""))
            run.check("reader stayed connected (tlm rate)", tlm >= 0.95 * 50 * args.seconds,
                      f"{tlm} tlm in about {args.seconds + 8:.0f} s of watching")
            run.check("UI ignored counter stayed 0", probe_result.get("ignoredMax") == 0,
                      f"max {probe_result.get('ignoredMax')} over {probe_result.get('samples')} samples; last "
                      f"{probe_result.get('last', {}).get('status')!r}")
            run.check("UI sent nothing", frames.get("sent") == 0, f"{frames.get('sent')} frames sent")
            run.check("UI in device mode throughout", probe_result.get("headerAlwaysLive") is True,
                      f"modes seen {probe_result.get('modesSeen')}")
    else:
        reader = by_name["reader"]
        types = reader.types()
        run.check("reader received only tlm", set(types) == {"tlm"}, f"{types}")
        run.check("reader stayed connected (tlm rate)", types.get("tlm", 0) >= 0.95 * 50 * args.seconds, f"{types}")
        run.check("reader sent nothing", not reader.sent, f"{len(reader.sent)} frames sent")
        reader.write_jsonl(run.dir / "reader.jsonl")

    # Generator and positive control.
    events_gen = [m for m in gen.messages() if m.get("type") == "event"]
    events_pinger = [m for m in pinger.messages() if m.get("type") == "event"]
    acks = [a for _label, a in log]
    run.check("generator commands acked", bool(log) and all(a is not None for a in acks),
              f"{len(log)} sent; acks {[(l, a.get('ok') if a else None, (a or {}).get('reason')) for l, a in log[:6]]}"
              + (" ..." if len(log) > 6 else ""))
    run.check("events were generated", len(events_gen) > 0,
              f"generator received {len(events_gen)} event(s): "
              f"{sorted({json.dumps({k: e.get(k) for k in ('event', 'mode', 'cause', 'name', 'detail') if e.get(k) is not None}) for e in events_gen})}"
              if events_gen else "no event reached the generator: the positive control below cannot pass, so the "
                                 "run proves nothing about the read-only rule")
    key = lambda e: (e.get("seq"), e.get("event"), e.get("mode"), e.get("cause"), e.get("name"), e.get("detail"))
    missing = [e for e in events_gen if key(e) not in {key(p) for p in events_pinger}]
    run.check("positive control: the pinger received the events", bool(events_gen) and not missing,
              f"pinger {len(events_pinger)}, generator {len(events_gen)}, missing at the pinger {len(missing)}")
    run.check("pinger frames", None, f"{pinger.types()}")
    run.check("generator frames", None, f"{gen.types()}")
    last = gen.last_tlm() or {}
    run.check("box state at the end", None, f"mode {last.get('mode')}, flags {last.get('flags')}, throttle {last.get('throttle')}")

    files = [pinger.write_jsonl(run.dir / "pinger.jsonl"), gen.write_jsonl(run.dir / "generator.jsonl")]
    if args.reader == "raw":
        files.append(run.dir / "reader.jsonl")
    ok, summaries = rc.check_schema(run, files, "t4")
    run.check("check-schema on every capture", ok, "; ".join(f"{k.split('/')[-1]}: {v}" for k, v in summaries.items()))
    return run.finish()


if __name__ == "__main__":
    sys.exit(main())
